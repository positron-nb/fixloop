const dict: Record<Lang, Record<MsgKey, string>> = { en, hi };

interface LangCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  toggle: () => void;
  t: (k: MsgKey) => string;
  pick: (b: Bilingual | undefined | null) => string;
}

const Ctx = createContext<LangCtx | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('fixloop.lang');
    if (saved === 'en' || saved === 'hi') return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.toLowerCase().startsWith('hi') ? 'hi' : 'en';
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem('fixloop.lang', l);
    } catch {
      /* ignore */
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    I18n.setLanguage(lang);
  }, [lang]);
  const value = useMemo<LangCtx>(
    () => ({
      lang,
      setLang,
      toggle: () => setLang(lang === 'en' ? 'hi' : 'en'),
      t: (k) => dict[lang][k] ?? en[k],
      pick: (b) => (b ? (lang === 'hi' ? b.hi : b.en) : ''),
    }),
    [lang, setLang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang(): LangCtx {
  const v = useContext(Ctx);
  if (!v) throw new Error('useLang outside LangProvider');
  return v;
}

export const dictionaries = dict;
